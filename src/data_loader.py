# DataLoader summary
# ============================================================

def dataloader_summary(
    dataloader_bundle,
):
    """
    Return a JSON-serializable DataLoader summary.

    No local absolute paths are included.
    """

    dataset = dataloader_bundle[
        "dataset"
    ]

    settings = dataloader_bundle[
        "settings"
    ]

    train_loader = dataloader_bundle[
        "train_loader"
    ]

    validation_loader = (
        dataloader_bundle[
            "validation_loader"
        ]
    )

    test_loader = dataloader_bundle[
        "test_loader"
    ]

    n_train = len(
        dataset[
            "sample_id_train"
        ]
    )

    n_validation = len(
        dataset[
            "sample_id_validation"
        ]
    )

    n_test = len(
        dataset[
            "sample_id_test"
        ]
    )

    train_batch_size = (
        train_loader.batch_size
    )

    if settings[
        "drop_last_training"
    ]:
        train_samples_per_epoch = (
            n_train
            // train_batch_size
            * train_batch_size
        )

    else:
        train_samples_per_epoch = (
            n_train
        )

    if settings[
        "drop_last_evaluation"
    ]:
        validation_samples_evaluated = (
            n_validation
            // validation_loader.batch_size
            * validation_loader.batch_size
        )

        test_samples_evaluated = (
            n_test
            // test_loader.batch_size
            * test_loader.batch_size
        )

    else:
        validation_samples_evaluated = (
            n_validation
        )

        test_samples_evaluated = (
            n_test
        )

    summary = {
        "n_train": (
            n_train
        ),

        "n_validation": (
            n_validation
        ),

        "n_test": (
            n_test
        ),

        "train_samples_per_epoch": int(
            train_samples_per_epoch
        ),

        "validation_samples_evaluated": int(
            validation_samples_evaluated
        ),

        "test_samples_evaluated": int(
            test_samples_evaluated
        ),

        "input_dimension": int(
            dataset[
                "X_train"
            ].shape[1]
        ),

        "output_dimension": int(
            dataset[
                "Y_train"
            ].shape[1]
        ),

        "targets": (
            dataset[
                "target_names"
            ].tolist()
        ),

        "tensor_dtype": str(
            dataloader_bundle[
                "dtype"
            ]
        ),

        "device": str(
            dataloader_bundle[
                "device"
            ]
        ),

        "random_seed": int(
            dataloader_bundle[
                "random_seed"
            ]
        ),

        "train_batch_size": int(
            train_loader.batch_size
        ),

        "evaluation_batch_size": int(
            validation_loader.batch_size
        ),

        "train_batches_per_epoch": int(
            len(
                train_loader
            )
        ),

        "validation_batches": int(
            len(
                validation_loader
            )
        ),

        "test_batches": int(
            len(
                test_loader
            )
        ),

        "shuffle_training": bool(
            settings[
                "shuffle_training"
            ]
        ),

        "shuffle_validation": False,

        "shuffle_test": False,

        "drop_last_training": bool(
            settings[
                "drop_last_training"
            ]
        ),

        "drop_last_evaluation": bool(
            settings[
                "drop_last_evaluation"
            ]
        ),

        "num_workers": int(
            settings[
                "num_workers"
            ]
        ),

        "pin_memory_requested": (
            settings[
                "pin_memory_requested"
            ]
        ),

        "pin_memory_effective": bool(
            settings[
                "pin_memory_effective"
            ]
        ),
    }

    return summary


